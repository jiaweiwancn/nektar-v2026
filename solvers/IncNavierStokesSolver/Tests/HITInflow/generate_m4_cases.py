#!/usr/bin/env python3
"""Generate small Homogeneous1D/full-3D HIT inlet comparison inputs.

This prepares reproducible XML, not numerical validation. Run solvers and
comparisons in the authoritative Linux environment described by AGENTS.md.
The M1 experimental inputs and all existing M3 fixtures remain unchanged.
"""

import argparse
from copy import deepcopy
import importlib.util
import math
from pathlib import Path
import xml.etree.ElementTree as ET


FIXTURES = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("hit_m3_fixtures", FIXTURES / "generate_m3_cases.py")
m3 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(m3)
TWO_PI = m3.TWO_PI
VARIABLES = m3.VARIABLES


def xy_geometry():
    """Four quads; use the established ChanFlow_3DH1D edge convention."""
    geometry = ET.Element("GEOMETRY", DIM="2", SPACE="2")
    vertices = m3.sub(geometry, "VERTEX")
    for iy in range(3):
        for ix in range(3):
            m3.sub(vertices, "V", f"{m3.number(ix / 2)} {m3.number(iy * math.pi)} 0",
                   ID=str(3 * iy + ix))
    edges = m3.sub(geometry, "EDGE")
    endpoints = ((0, 1), (1, 2), (0, 3), (1, 4), (2, 5), (3, 4),
                 (4, 5), (3, 6), (4, 7), (5, 8), (6, 7), (7, 8))
    for index, (first, second) in enumerate(endpoints):
        m3.sub(edges, "E", f"{first} {second}", ID=str(index))
    elements = m3.sub(geometry, "ELEMENT")
    for index, sides in enumerate(((0, 3, 5, 2), (1, 4, 6, 3),
                                    (5, 8, 10, 7), (6, 9, 11, 8))):
        m3.sub(elements, "Q", " ".join(map(str, sides)), ID=str(index))
    composites = m3.sub(geometry, "COMPOSITE")
    for index, description in enumerate(("Q[0-3]", "E[2,7]", "E[4,9]",
                                         "E[0,1]", "E[10,11]")):
        m3.sub(composites, "C", description, ID=str(index))
    m3.sub(geometry, "DOMAIN", "C[0]")
    return geometry


def parameter(root, name, value):
    parameters = root.find("./CONDITIONS/PARAMETERS")
    for entry in parameters:
        if entry.text.split("=", 1)[0].strip().lower() == name.lower():
            entry.text = f"{name} = {m3.number(value)}"
            return
    m3.sub(parameters, "P", f"{name} = {m3.number(value)}")


def solver_info(root, name, value):
    info = root.find("./CONDITIONS/SOLVERINFO")
    for entry in info:
        if entry.attrib["PROPERTY"].lower() == name.lower():
            entry.set("VALUE", value)
            return
    m3.sub(info, "I", PROPERTY=name, VALUE=value)


def make_case(homogeneous, kind, modes, homogeneous_modes, dt, steps):
    root = ET.fromstring(m3.make_case("stochastic", num_modes=modes))
    root.insert(0, ET.Comment(" Generated by generate_m4_cases.py; sparse inlet REF=7. "))
    parameter(root, "TimeStep", dt)
    parameter(root, "NumSteps", steps)
    parameter(root, "IO_InfoSteps", steps)
    parameter(root, "IterativeSolverTolerance", 1e-12)
    solver_info(root, "GlobalSysSoln", "IterativeStaticCond")
    root.find("./HITINFLOW/REGION/SYNTHESIS").set("RECORDDURATION", m3.number(dt * steps))
    if homogeneous:
        old = root.find("GEOMETRY")
        position = list(root).index(old)
        root.remove(old)
        root.insert(position, xy_geometry())
        solver_info(root, "HOMOGENEOUS", "1D")
        parameter(root, "HomModesZ", homogeneous_modes)
        parameter(root, "LZ", TWO_PI)
        for path, key in (("./CONDITIONS/BOUNDARYREGIONS", "ID"),
                          ("./CONDITIONS/BOUNDARYCONDITIONS", "REF")):
            parent = root.find(path)
            for entry in list(parent):
                if entry.attrib[key] in ("31", "32"):
                    parent.remove(entry)
    spectrum = root.find("./HITINFLOW/REGION/SPECTRUM")
    if kind == "tabulated":
        spectrum.attrib = {"TYPE": "Tabulated", "FILE": "m4-shell-spectrum.dat",
                           "INTERPOLATION": "Linear", "LOW": "Zero", "HIGH": "Zero",
                           "NORMALIZATION": "TargetRMS", "RMS": "0.05"}
    elif kind == "mean-only":
        spectrum.set("RMS", "0")
        m3.function(root.find("CONDITIONS"), "ExactSolution", ["Ubar", "0", "0", "0"])
    elif kind == "fftw":
        if not homogeneous:
            raise ValueError("The FFT comparison uses Homogeneous1D")
        solver_info(root, "USEFFT", "FFTW")
    return root


def serialise(root):
    ET.indent(root, space="    ")
    return ET.tostring(root, encoding="unicode", xml_declaration=True) + "\n"


def write_cases(output, modes=8, homogeneous_modes=8, dt=0.001, steps=20):
    if modes < 4 or homogeneous_modes < 4 or homogeneous_modes % 2:
        raise ValueError("Use expansion modes >=4 and an even homogeneous count >=4")
    if not math.isfinite(dt) or dt <= 0 or steps < 2 or steps % 2:
        raise ValueError("Use a positive finite dt and a positive even step count >=2")
    output.mkdir(parents=True, exist_ok=True)
    cases = {}
    for homogeneous, representation in ((True, "h1d"), (False, "full3d")):
        for kind in ("von-karman", "mean-only", "tabulated"):
            name = f"m4-{representation}-{kind}.xml"
            cases[name] = make_case(homogeneous, kind, modes, homogeneous_modes, dt, steps)
        segment = deepcopy(cases[f"m4-{representation}-von-karman.xml"])
        parameter(segment, "NumSteps", steps // 2)
        parameter(segment, "IO_InfoSteps", steps // 2)
        parameter(segment, "IO_CheckSteps", steps // 2)
        cases[f"m4-{representation}-segment.xml"] = segment
        restart = deepcopy(cases[f"m4-{representation}-von-karman.xml"])
        parameter(restart, "NumSteps", steps // 2)
        parameter(restart, "IO_InfoSteps", steps // 2)
        initial = restart.find("./CONDITIONS/FUNCTION[@NAME='InitialConditions']")
        initial.clear()
        initial.set("NAME", "InitialConditions")
        m3.sub(initial, "F", VAR=",".join(VARIABLES),
               FILE=f"m4-{representation}-segment_1.chk")
        cases[f"m4-{representation}-restart.xml"] = restart
    cases["m4-h1d-fftw.xml"] = make_case(True, "fftw", modes, homogeneous_modes, dt, steps)
    filtered = deepcopy(cases["m4-h1d-segment.xml"])
    parameter(filtered, "IO_CheckSteps", 0)
    filters = m3.sub(filtered, "FILTERS")
    checkpoint = m3.sub(filters, "FILTER", TYPE="Checkpoint")
    m3.sub(checkpoint, "PARAM", "m4-h1d-filter", NAME="OutputFile")
    m3.sub(checkpoint, "PARAM", str(steps // 2), NAME="OutputFrequency")
    cases["m4-h1d-checkpoint-filter.xml"] = filtered
    filtered_restart = deepcopy(cases["m4-h1d-restart.xml"])
    filtered_restart.find("./CONDITIONS/FUNCTION[@NAME='InitialConditions']/F").set(
        "FILE", "m4-h1d-filter_1.chk")
    cases["m4-h1d-filter-restart.xml"] = filtered_restart
    for name, root in cases.items():
        (output / name).write_text(serialise(root), encoding="utf-8")
    (output / "m4-shell-spectrum.dat").write_bytes((FIXTURES / "m3-narrow-band.dat").read_bytes())
    return sorted(cases)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=FIXTURES)
    parser.add_argument("--modes", type=int, default=8, help="Polynomial expansion modes (default: 8)")
    parser.add_argument("--homogeneous-modes", type=int, default=8,
                        help="Full real Fourier packing size (default: 8)")
    parser.add_argument("--dt", type=float, default=0.001)
    parser.add_argument("--steps", type=int, default=20,
                        help="Even number of steps in the uninterrupted record")
    args = parser.parse_args()
    try:
        names = write_cases(args.output_dir, args.modes, args.homogeneous_modes,
                            args.dt, args.steps)
    except ValueError as error:
        parser.error(str(error))
    print(f"Generated {len(names)} M4 sessions and a shell spectrum in {args.output_dir}")


if __name__ == "__main__":
    main()
